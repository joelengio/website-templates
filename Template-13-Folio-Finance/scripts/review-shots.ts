/**
 * Captures full-page screenshots of the key routes at desktop and mobile widths and assembles labelled contact
 * sheets into review/ for visual review. Requires a running preview server (npm run preview) and Chromium.
 *   PW_CHROMIUM_PATH=/path/to/chromium npm run review:shots
 */
import { chromium } from '@playwright/test';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(root, 'review');
const shots = resolve(out, 'shots');
const base = process.env.BASE_URL ?? 'http://127.0.0.1:4173';

const routes: [string, string][] = [
  ['home', '/'], ['services', '/services'], ['service-detail', '/services/tax-planning'], ['industries', '/industries'],
  ['industry-detail', '/industries/startups'], ['about', '/about'], ['team', '/team'], ['team-profile', '/team/elena-marchetti'],
  ['pricing', '/pricing'], ['tools-compound', '/tools#compound'], ['tools-loan', '/tools#loan'], ['tools-breakeven', '/tools#break-even'],
  ['insights', '/insights'], ['article', '/insights/understanding-compound-growth'], ['booking', '/book?service=financial-planning'],
  ['contact', '/contact'], ['disclaimer', '/disclaimer'], ['not-found', '/no-such-page'],
];
const viewports = [
  { id: 'desktop', width: 1440, height: 900 },
  { id: 'mobile', width: 390, height: 844 },
];

rmSync(shots, { recursive: true, force: true });
mkdirSync(shots, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.PW_CHROMIUM_PATH || undefined, args: ['--no-sandbox'] });
const taken: Record<string, { label: string; file: string }[]> = { desktop: [], mobile: [] };
for (const vp of viewports) {
  const ctx = await browser.newContext({ viewport: { width: vp.width, height: vp.height }, reducedMotion: 'reduce' });
  const page = await ctx.newPage();
  for (const [name, path] of routes) {
    await page.goto(base + path, { waitUntil: 'networkidle' });
    await page.evaluate(async () => {
      document.querySelectorAll('img').forEach((i) => (i.loading = 'eager'));
      await Promise.all([...document.images].map((i) => (i.complete ? null : new Promise((r) => { i.onload = i.onerror = () => r(null); }))));
    });
    const file = `${vp.id}-${name}.jpg`;
    await page.screenshot({ path: resolve(shots, file), fullPage: true, type: 'jpeg', quality: 70 });
    taken[vp.id].push({ label: `${name} — ${path}`, file });
  }
  await ctx.close();
}

// Build the contact sheets by rendering a small HTML page with every screenshot (max height cropped for readability).
const sheetPage = await (await browser.newContext({ viewport: { width: 1800, height: 1000 } })).newPage();
for (const vp of viewports) {
  const cols = vp.id === 'desktop' ? 3 : 6;
  const cell = vp.id === 'desktop' ? 560 : 280;
  const crop = vp.id === 'desktop' ? 520 : 560;
  const items = taken[vp.id]
    .map((t) => `<figure><div class="img"><img src="data:image/jpeg;base64,${readFileSync(resolve(shots, t.file)).toString('base64')}" /></div><figcaption>${t.label}</figcaption></figure>`)
    .join('');
  const html = `<!doctype html><meta charset="utf-8"><style>
    body{margin:0;padding:20px;background:#1b2330;font:13px system-ui;color:#fff;width:${cols * (cell + 20) + 40}px}
    h1{font:600 18px system-ui;margin:0 0 14px}
    .grid{display:grid;grid-template-columns:repeat(${cols},${cell}px);gap:20px}
    figure{margin:0}.img{height:${crop}px;overflow:hidden;background:#fff;border-radius:4px}
    img{width:${cell}px;display:block}figcaption{padding:6px 2px;font-weight:600}</style>
    <h1>Folio Finance — ${vp.id} (${vp.width}px) — top of each page, full-page captures in review/shots/</h1><div class="grid">${items}</div>`;
  await sheetPage.setContent(html);
  await sheetPage.setViewportSize({ width: cols * (cell + 20) + 40, height: 800 });
  await sheetPage.screenshot({ path: resolve(out, `contact-sheet-${vp.id}.jpg`), fullPage: true, type: 'jpeg', quality: 72 });
}
writeFileSync(resolve(out, 'README.md'), `# Visual review\n\nGenerated by \`npm run review:shots\`.\n\n- \`contact-sheet-desktop.jpg\` — 1440px, top of each route\n- \`contact-sheet-mobile.jpg\` — 390px, top of each route\n- \`shots/\` — full-page captures per route\n`);
await browser.close();
console.log('Review sheets written to review/');
